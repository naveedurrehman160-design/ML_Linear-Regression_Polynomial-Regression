import matplotlib.pyplot as plt
import pandas as pd
import numpy as np

X = df[["YearsExperience"]]
y = df["Salary"]

linear_model = LinearRegression()
linear_model.fit(X, y)

X_plot = pd.DataFrame({
    "YearsExperience": np.linspace(
        X["YearsExperience"].min(),
        X["YearsExperience"].max(),
        300
    )
})

y_pred = linear_model.predict(X_plot)

plt.scatter(X["YearsExperience"], y, label="Actual Salary")
plt.plot(X_plot["YearsExperience"], y_pred, label="Linear Regression")

plt.xlabel("Years of Experience")
plt.ylabel("Salary")
plt.title("Years of Experience vs Salary - Linear Regression")
plt.legend()
plt.grid(True)
plt.show()

df = pd.read_csv("Salary_Data.csv")

from sklearn.preprocessing import PolynomialFeatures
from sklearn.linear_model import LinearRegression
X = df[["YearsExperience"]]
y = df["Salary"]

poly = PolynomialFeatures(degree=2)
X_poly = poly.fit_transform(X)

model = LinearRegression()
model.fit(X_poly, y)

experience=float(input("Enter the experience: "))
experience_poly=poly.fit_transform([[experience]])
prediction=model.predict(experience_poly)
print("Expected_Salary is: ",prediction[0])

from sklearn.preprocessing import PolynomialFeatures
from sklearn.linear_model import LinearRegression

poly = PolynomialFeatures(degree=2)
X_poly = poly.fit_transform(X)

poly_model = LinearRegression()
poly_model.fit(X_poly, y)

X_plot_poly = poly.transform(X_plot)
y_poly_pred = poly_model.predict(X_plot_poly)

plt.scatter(X["YearsExperience"], y, label="Actual Salary")
plt.plot(X_plot["YearsExperience"], y_poly_pred, label="Polynomial Regression")

plt.xlabel("Years of Experience")
plt.ylabel("Salary")
plt.title("Years of Experience vs Salary - Polynomial Regression")
plt.legend()
plt.grid(True)
plt.show()